#!/usr/bin/env python3
"""Generate MenuCommands.h from the native menu command catalog."""
import argparse
import csv
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def catalog(path):
    with path.open(newline="", encoding="ascii") as source:
        rows = list(csv.DictReader(source, delimiter="\t"))
    pairs, commands = set(), set()
    for row in rows:
        row["menu"], row["item"] = int(row["menu"]), int(row["item"])
        pair = row["menu"], row["item"]
        command = row["command"]
        if (not all(0 < n <= 32767 for n in pair)
                or pair in pairs or command in commands
                or not re.fullmatch(r"MC_[A-Z0-9_]+", command)
                or command in ("MC_NONE", "MC_COUNT")
                or row["implemented"] not in ("0", "1")):
            raise ValueError("invalid or duplicate menu command: " + str(row))
        pairs.add(pair)
        commands.add(command)
    return rows


def render(rows):
    lines = ["/* Generated by tools/menu_catalog.py. Edit the catalog, then regenerate. */",
             "#ifndef GH_MENU_COMMANDS_H", "#define GH_MENU_COMMANDS_H",
             "enum { MC_NONE = 0,"]
    lines += ["    " + row["command"] + "," for row in rows]
    lines += ["    MC_COUNT", "};", "static short MenuCommand(short menu, short item) {",
              "    switch (menu) {"]
    for menu in dict.fromkeys(row["menu"] for row in rows):
        lines += ["    case %d:" % menu, "        switch (item) {"]
        lines += ["        case %d: return %s;" % (row["item"], row["command"])
                  for row in rows if row["menu"] == menu]
        lines += ["        }", "        break;"]
    lines += ["    }", "    return MC_NONE;", "}",
              "static int MenuImplemented(short command) {", "    switch (command) {"]
    lines += ["    case " + row["command"] + ":" for row in rows if row["implemented"] == "1"]
    lines += ["        return 1;", "    }", "    return 0;", "}", "#endif"]
    return ("\r".join(lines) + "\r").encode("mac_roman")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(catalog(ROOT / "tools/menu_catalog.tsv"))
    target = ROOT / "SRC/MenuCommands.h"
    if args.check:
        if target.read_bytes() != generated:
            parser.error("MenuCommands.h differs from the catalog")
        print("Menu command header matches catalog")
    else:
        target.write_bytes(generated)


if __name__ == "__main__":
    main()
