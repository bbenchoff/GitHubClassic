#!/usr/bin/env python3
"""Generate the native PEM header from explicitly pinned public root inputs.

This does not download certificates or decide which authorities to trust.
Changing the trust set requires reviewing both the input and its manifest.
"""
import argparse
import hashlib
import json
from pathlib import Path
import ssl

ROOT = Path(__file__).resolve().parents[1]


def generate(directory):
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    lines = ["/* Public CA roots; generated by tools/make_trust_roots.py.",
             "   R46 and E46 support GitHub RSA/ECDSA chains; USERTrust ECC is a fallback. */",
             "static const char GH_ROOT_PEM[] ="]
    names, fingerprints = set(), set()
    for entry in manifest["certificates"]:
        name = entry["file"]
        if Path(name).name != name or name in names:
            raise ValueError("invalid or repeated root input name")
        names.add(name)
        pem = (directory / name).read_text(encoding="ascii")
        if (not pem.startswith("-----BEGIN CERTIFICATE-----\n")
                or not pem.endswith("-----END CERTIFICATE-----\n")
                or pem.count("-----BEGIN CERTIFICATE-----") != 1):
            raise ValueError("expected exactly one PEM certificate: " + name)
        fingerprint = hashlib.sha256(ssl.PEM_cert_to_DER_cert(pem)).hexdigest()
        if fingerprint != entry["sha256_der"] or fingerprint in fingerprints:
            raise ValueError("root fingerprint mismatch or duplicate: " + name)
        fingerprints.add(fingerprint)
        for line in pem.splitlines():
            if any(c not in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=- " for c in line):
                raise ValueError("invalid PEM characters: " + name)
            lines.append('    "' + line + '\\n"')
    if not names:
        raise ValueError("empty trust set")
    return ("\r".join([*lines, ";", ""]) ).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(ROOT / "tools/trust-roots")
    target = ROOT / "SRC/TrustRoots.h"
    if args.check:
        if target.read_bytes() != generated:
            parser.error("TrustRoots.h differs from the pinned root inputs")
        print("Trust root header matches pinned certificates")
    else:
        target.write_bytes(generated)


if __name__ == "__main__":
    main()
